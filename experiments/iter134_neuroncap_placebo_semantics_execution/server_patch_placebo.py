"""Iteration 134 placebo patch: semantics-scrambled, budget-matched.

Inherits the released union's actuator byte-for-byte (the latched zero trajectory of
experiments/iter15_latch_release/server_patch_union_release.py) and receives its firing from a
frozen donor schedule instead of from the world.

The intervention function reads exactly two things: a per-run frame counter, and the frozen
donor schedule keyed by (pair, run). It does not inspect the planner's auxiliary outputs, the
detected objects, their scores, their forecasts, their identities, the ego pose, or the episode
outcome. It cannot compute a risk quantity because it never observes anything to compute one
from. That is the point of the control: same actuator, same budget, no semantics.

The donor schedule is generated by extract_donor_schedules.py from the committed released-union
decision log and is hash-bound in the launch manifest before any episode runs.
"""
import subprocess

SRV = '/opt/sentinel-stack/UniAD/inference/server.py'
subprocess.run(['git', '-C', '/opt/sentinel-stack/UniAD', 'checkout', '--', 'inference/server.py'],
               check=True)
src = open(SRV).read()

HELPERS = '''
# ---- Sentinel iter134: semantics-scrambled budget-matched placebo -------------------------------
# Identical actuator to the released union (latched zero trajectory). The firing decision comes
# from a frozen donor schedule of frame indices, derived from a DIFFERENT scenario pair and a
# DIFFERENT seed of the committed released-union log. This function observes nothing about the
# world. It knows only which frame number it is on.
import json as _sjson, os as _sos
_SENTINEL_LOG = _sos.environ.get("SENTINEL_LOG", "/model/sentinel_placebo.jsonl")
_SENTINEL_SCHED_PATH = _sos.environ.get("SENTINEL_PLACEBO_SCHEDULE", "/model/donor_schedules.json")
_SENTINEL_PAIR = _sos.environ.get("SENTINEL_PLACEBO_PAIR", "")
_sentinel_run = {"i": -1, "k": 0}
try:
    with open(_SENTINEL_SCHED_PATH) as _sf:
        _SENTINEL_SCHEDULES = _sjson.load(_sf)["schedules"]
except Exception:
    _SENTINEL_SCHEDULES = {}


def _sentinel_reset():
    _sentinel_run["i"] += 1
    _sentinel_run["k"] = 0
    try:
        with open(_SENTINEL_LOG, "a") as f:
            f.write(_sjson.dumps({"reset": True, "run": _sentinel_run["i"],
                                  "pair": _SENTINEL_PAIR}) + "\\n")
    except Exception:
        pass


def _sentinel_scheduled_frames():
    row = _SENTINEL_SCHEDULES.get("%s/%d" % (_SENTINEL_PAIR, _sentinel_run["i"]))
    if not row:
        return set(), None
    return set(row.get("brake_frames") or []), row


def _sentinel_intervene(out, data):
    base = [[float(x), float(y)] for x, y in out.trajectory.tolist()]
    if _sos.environ.get("SENTINEL_ENABLED", "0") != "1":
        return base
    k = _sentinel_run["k"]
    _sentinel_run["k"] += 1
    try:
        frames, row = _sentinel_scheduled_frames()
        if row is None:
            with open(_SENTINEL_LOG, "a") as f:
                f.write(_sjson.dumps({"schedule_missing": True, "run": _sentinel_run["i"],
                                      "pair": _SENTINEL_PAIR, "k": k}) + "\\n")
            return base
        with open(_SENTINEL_LOG, "a") as f:
            f.write(_sjson.dumps({"frame": True, "run": _sentinel_run["i"], "k": k}) + "\\n")
        if k in frames:
            with open(_SENTINEL_LOG, "a") as f:
                f.write(_sjson.dumps({"brake": True, "run": _sentinel_run["i"], "k": k,
                                      "pair": _SENTINEL_PAIR,
                                      "donor": "%s/%s/%s" % (row.get("donor_class"),
                                                             row.get("donor_seq"),
                                                             row.get("donor_run"))}) + "\\n")
            return [[0.0, 0.0] for _ in range(len(base))]
    except Exception as e:
        try:
            with open(_SENTINEL_LOG, "a") as f:
                f.write(_sjson.dumps({"intervene_err": str(e)}) + "\\n")
        except Exception:
            pass
    return base


'''

anchor = '@app.get("/alive")'
assert anchor in src
src = src.replace(anchor, HELPERS + anchor, 1)
infer_old = ("    uniad_output = uniad_runner.forward_inference(uniad_input)\n"
             "    return InferenceOutputs(\n"
             "        trajectory=uniad_output.trajectory.tolist(),")
infer_new = ("    uniad_output = uniad_runner.forward_inference(uniad_input)\n"
             "    return InferenceOutputs(\n"
             "        trajectory=_sentinel_intervene(uniad_output, data),")
assert infer_old in src
src = src.replace(infer_old, infer_new, 1)
reset_old = "async def reset_runner() -> bool:\n    uniad_runner.reset()"
reset_new = "async def reset_runner() -> bool:\n    _sentinel_reset()\n    uniad_runner.reset()"
assert reset_old in src
src = src.replace(reset_old, reset_new, 1)
open(SRV, "w").write(src)
print("PLACEBO_PATCHED")
